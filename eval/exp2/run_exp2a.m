function run_exp2a()
%RUN_EXP2A Experiment 2a: road-order and direction-state optimization.
% Run this file directly in MATLAB. It constructs every task from the
% measured orchard road vectors and DEM used by Experiment 1, generates
% each road's photographic waypoints with the same footprint constraints,
% and writes reproducible numerical results to <project>/results/exp2.
%
% Compared methods:
%   1) fixed input order and fixed forward direction;
%   2) direction-aware nearest-neighbour order followed by exact 2-state DP;
%   3) joint-encoding GA for both road order and direction;
%   4) proposed GA-DP: GA for road order and exact 2-state DP for direction.
% Exact subset DP (R <= 10) and an independently validated exact MILP
% (R = 20) provide the optimality-gap references.
%
% Required toolbox: Mapping Toolbox. No synthetic road, waypoint, or
% elevation data are generated by this experiment.

close all;

scriptDir = fileparts(mfilename('fullpath'));
addpath(scriptDir);
projectRoot = fileparts(fileparts(scriptDir));
dataDir = fullfile(projectRoot, 'dem');
outputDir = fullfile(projectRoot, 'results', 'exp2');
figureDataFile = fullfile(projectRoot, 'results', 'figures', ...
    'selected_routes.mat');
if ~isfolder(outputDir)
    mkdir(outputDir);
end
assert(isfolder(dataDir), 'Road/DEM directory not found: %s', dataDir);
assert(exist('shaperead', 'file') == 2 && ...
    exist('readgeoraster', 'file') == 2, ...
    'Mapping Toolbox is required to read the measured road and DEM data.');
assert(exist('intlinprog', 'file') == 2, ...
    ['Optimization Toolbox is required to certify the R=20 exact ', ...
    'reference solution.']);

%% Parameters fixed by the manuscript and Experiment 1
param.crs = 4542;
param.routeLength = 500;              % m
param.centerlineSpacing = 2;          % m
param.windowStride = 20;              % m
param.elevationSmooth = 40;           % m
param.eastingLimits = [5.060e5, 5.073e5];
param.maxAbsGradeP95 = 0.30;
param.mainRoadWidth = 4.5;            % m
param.fieldRoadWidth = 3.5;           % m
param.cameraDistance = 30;            % m
param.fovAlong = deg2rad(73.68);      % rad
param.fovAcross = deg2rad(53.08);     % rad
param.minimumOverlap = 0.80;
param.minimumRoadCoverage = 1.00;
param.footprintAlong = 2*param.cameraDistance*tan(param.fovAlong/2);
param.footprintAcross = 2*param.cameraDistance*tan(param.fovAcross/2);
param.maximumSpacing = (1-param.minimumOverlap)*param.footprintAlong;
% DJI Terra's official Phantom-4 route-planning example uses 4 m/s.  With
% the 8.99 m largest feasible observation interval this gives 2.25 s
% between exposures; it is an imaging setting, not the aircraft max speed.
param.photographySpeed = 4;           % m/s, fixed during road imaging

% Section 3.3 directed 3-D multirotor power model. Parameters follow Gong
% et al., IEEE TAES 59(6), 7409-7422 (2023), Table I and Sec. IV-D.
% The objective J is reported in kJ.
param.energy.rotorCount = 4;
param.energy.profileDrag = 0.011;
param.energy.airDensity = 1.168;       % kg/m^3
param.energy.rotorSolidity = 0.045;
param.energy.rotorDiscArea = 0.214;    % m^2 per rotor
param.energy.thrustCoefficient = 0.001195;
param.energy.inducedCorrection = 0.11;
param.energy.weight = 20;              % N, reference platform
param.energy.inducedVelocity = 6.325;  % m/s
param.energy.flatPlateHorizontal = 0.009; % m^2
param.energy.flatPlateVertical = 0.377;   % m^2
param.energy.horizontalSpeedMax = 15;  % m/s
param.energy.ascentSpeedMax = 6;       % m/s
param.energy.descentSpeedMax = 3;      % m/s
param.energy.minimumSpeed = 1;         % m/s, transfer-time upper bound

% Section 3.3 terrain-aware transition graph. Horizontal discretization is
% tied to the measured DEM resolution (~10 m); the 10 m/20 m refinement
% audit below records sensitivity on representative directed transfers.
param.terrain.clearance = 20;          % m operational terrain clearance
param.terrain.demErrorMargin = 5;      % m explicit DEM/model margin
param.terrain.longitudinalStep = 20;   % m
param.terrain.lateralStep = 20;        % m
param.terrain.lateralHalfWidth = 120;  % m, local corridor cap
param.terrain.verticalOffsets = [0,20]; % m above clearance surface
param.terrain.edgeSampleStep = 5;      % m, half the DEM cell size

%% Reproducible experimental settings (solver settings, not physical data)
cfg.scales = [5, 10, 20];
cfg.taskInstancesPerScale = 10;
cfg.independentGaRuns = 20;
cfg.taskSeed = 20260904;
cfg.gaSeed = 20262000;
% Road 1 is reserved exclusively for the two fixed mission boundary states;
% it is never included among the target roads.  The remaining 24 measured
% segments support ten distinct R=20 task sets.
cfg.routeLibraryTarget = 25;
cfg.minimumRouteLibrarySize = max(cfg.scales)+1;
cfg.subsetDpMaximumR = 10;
cfg.exactMaximumR = max(cfg.scales);
cfg.routeCacheVersion = 'exp2a-real-road-v3-open-boundary';

cfg.milp.relativeGapTolerance = 1e-9;
cfg.milp.absoluteGapTolerance = 1e-6;
cfg.milp.maximumTime_s = 3600;

cfg.ga.populationSize = 60;
cfg.ga.maximumGenerations = 150;
% Both stochastic methods receive exactly the same 60 x 151 objective
% evaluations (initial population plus 150 generations).
cfg.ga.minimumGenerations = cfg.ga.maximumGenerations;
cfg.ga.stallGenerations = cfg.ga.maximumGenerations+1;
cfg.ga.tournamentSize = 3;
cfg.ga.eliteCount = 2;
cfg.ga.crossoverRate = 0.90;
cfg.ga.permutationMutationRate = 0.25;
cfg.ga.improvementTolerance = 1e-10;

assert(abs(param.footprintAlong-44.95) < 0.03);
assert(abs(param.maximumSpacing-8.99) < 0.01);
assert(param.footprintAcross >= param.mainRoadWidth);
assert(cfg.ga.eliteCount >= 1 && cfg.ga.eliteCount < cfg.ga.populationSize);
assert(mod(cfg.ga.populationSize, 2) == 0);

paths.major = findInput(dataDir, {'major_roads.shp', '大路.shp'});
paths.minor = findInput(dataDir, {'minor_roads.shp', '小路.shp'});
paths.dem = findInput(dataDir, {'dem.tif', 'dem+.tif'});
paths.selectedRoutes = figureDataFile;
param.terrain.demPath = paths.dem;

parameterContract = buildParameterContract(param,cfg);
writetable(parameterContract,fullfile(outputDir, ...
    'exp2_parameter_contract.csv'),'Encoding','UTF-8');

if ~isfile(figureDataFile)
    plotDir = fullfile(projectRoot, 'plot');
    addpath(plotDir);
    plot_orchard_road_network(dataDir, ...
        fullfile(projectRoot, 'results', 'figures'));
end
assert(isfile(figureDataFile), ...
    'Experiment-1 selected-road file not found: %s', figureDataFile);

fprintf('Experiment 2a: measured-road order/direction comparison\n');
fprintf('  Task scales: %s roads; %d real task sets per scale\n', ...
    strjoin(string(cfg.scales), ', '), cfg.taskInstancesPerScale);
fprintf('  GA repetitions: %d per task set and stochastic method\n', ...
    cfg.independentGaRuns);

%% Build or load the measured-road waypoint library
cachePath = fullfile(outputDir, 'exp2a_route_library.mat');
cacheSignature = buildCacheSignature(paths, param, cfg);
[routeLibrary, cacheUsed] = loadOrBuildRouteLibrary( ...
    cachePath, cacheSignature, paths, param, cfg);
routeLibrary = routeLibrary(1:cfg.routeLibraryTarget);
assert(numel(routeLibrary) >= cfg.minimumRouteLibrarySize, ...
    ['At least %d non-overlapping real 500 m road segments are required ', ...
    'to form ten distinct R=20 task sets; only %d were generated.'], ...
    cfg.minimumRouteLibrarySize, numel(routeLibrary));
if cacheUsed
    fprintf('  Reused validated real-road waypoint library: %d segments\n', ...
        numel(routeLibrary));
else
    fprintf('  Built real-road waypoint library: %d segments\n', ...
        numel(routeLibrary));
end

% Distinct, fixed mission boundary points are used by every method and task.
% They are the opposite ends of the measured manuscript Road A major-road
% corridor and are fixed before task sampling.
assert(routeLibrary(1).isPaperRoadA, ...
    'The first library route must be the measured manuscript Road A.');
launchPoint = routeLibrary(1).waypoints(1, :);
recoveryPoint = routeLibrary(1).waypoints(end, :);
assert(all(isfinite([launchPoint,recoveryPoint])) && ...
    norm(launchPoint-recoveryPoint) > 1);

instances = buildTaskInstances(routeLibrary, cfg);
assert(all(arrayfun(@(x) ~ismember(1,x.libraryIndices),instances)), ...
    'The boundary corridor must not also be a target road.');
instanceTable = buildInstanceTable(instances, routeLibrary);
writetable(instanceTable, fullfile(outputDir, ...
    'exp2a_task_instances.csv'), 'Encoding', 'UTF-8');

% Precompute every directed endpoint-to-endpoint transfer once. All task
% instances and all comparison methods then use exactly the same terrain-
% safe path and directed physical-energy cost for a given boundary pair.
[terrain.dem,terrain.reference] = readgeoraster(paths.dem,'OutputType','double');
terrain.dem(terrain.dem < -10000) = NaN;
[terrain.latitude,terrain.longitude] = geographicGrid(terrain.reference);
[terrain.x,terrain.y] = projfwd(projcrs(param.crs), ...
    terrain.latitude,terrain.longitude);
validTerrain = isfinite(terrain.dem) & isfinite(terrain.x) & isfinite(terrain.y);
terrain.interpolant = scatteredInterpolant(terrain.x(validTerrain), ...
    terrain.y(validTerrain),terrain.dem(validTerrain),'linear','none');
terrainGraph = struct('interpolant',terrain.interpolant);
masterCachePath = fullfile(outputDir,'exp2a_master_problem.mat');
plannerSignature = sourceFileSignature(fullfile(scriptDir, ...
    'uav_terrain_transition.m'));
energyCodeSignature = sourceFileSignature(fullfile(scriptDir, ...
    'uav_edge_energy.m'));
masterSignature = sprintf(['schema5-position-only|R%d|vp%.6g|dx%.6g|dy%.6g|', ...
    'yw%.6g|clr%.6g|eps%.6g|edge%.6g|z%s|E%s'], ...
    numel(routeLibrary),param.photographySpeed, ...
    param.terrain.longitudinalStep,param.terrain.lateralStep, ...
    param.terrain.lateralHalfWidth, ...
    param.terrain.clearance,param.terrain.demErrorMargin, ...
    param.terrain.edgeSampleStep, ...
    mat2str(param.terrain.verticalOffsets),energySignature(param.energy));
masterSignature = sprintf('%s|planner=%s|energyCode=%s',masterSignature, ...
    plannerSignature,energyCodeSignature);
if isfile(masterCachePath)
    masterCache = load(masterCachePath,'masterProblem','masterCacheMeta');
else
    masterCache = struct();
end
if isfield(masterCache,'masterProblem') && ...
        isfield(masterCache,'masterCacheMeta') && ...
        strcmp(masterCache.masterCacheMeta.signature,masterSignature)
    masterProblem = masterCache.masterProblem;
    fprintf('  Reused terrain-aware directed transition library.\n');
else
    fprintf('  Precomputing terrain-aware directed transition library...\n');
    masterProblem = buildRoutingProblem(routeLibrary,launchPoint, ...
        recoveryPoint,param,terrainGraph);
    masterCacheMeta.signature = masterSignature;
    masterCacheMeta.generatedAt = datetime('now','TimeZone','Asia/Shanghai');
    save(masterCachePath,'masterProblem','masterCacheMeta','-v7.3');
end
runTerrainDiscretizationAudit(routeLibrary,terrainGraph,param,outputDir);

%% Run all methods
rawRows = repmat(emptyRawRow(), 0, 1);
totalInstances = numel(instances);
experimentStart = tic;
for instanceIndex = 1:totalInstances
    instance = instances(instanceIndex);
    problem = subsetRoutingProblem(masterProblem,instance.libraryIndices);
    R = instance.R;

    fprintf('\n[%d/%d] %s (%d roads)\n', instanceIndex, ...
        totalInstances, instance.id, R);

    if R <= cfg.subsetDpMaximumR
        timer = tic;
        exactSolution = solveExactSubsetDP(problem);
        exactRuntime = toc(timer);
        validateSolution(exactSolution, problem, param);
        exactJ = exactSolution.J;

        if R <= 5
            bruteJ = bruteForceAllCost(problem);
            assert(costsEqual(exactJ, bruteJ), ...
                'Subset DP failed the R=5 exhaustive audit.');
        end
        % An independently formulated MILP must reproduce the subset-DP
        % optimum before it is trusted for the R=20 reference.
        milpAudit = solveExactMILP(problem, cfg.milp);
        validateSolution(milpAudit, problem, param);
        assert(costsEqual(milpAudit.J, exactJ), ...
            'Exact MILP and subset DP disagree.');
    else
        timer = tic;
        exactSolution = solveExactMILP(problem, cfg.milp);
        exactRuntime = toc(timer);
        validateSolution(exactSolution, problem, param);
        exactJ = exactSolution.J;
    end

    timer = tic;
    fixedSolution = evaluateSolution(1:R, ones(1, R), problem);
    fixedRuntime = toc(timer);
    validateSolution(fixedSolution, problem, param);
    fixedJ = fixedSolution.J;

    timer = tic;
    nnOrder = nearestNeighbourOrder(problem);
    nnSolution = solveFixedOrderDP(nnOrder, problem);
    nnRuntime = toc(timer);
    validateSolution(nnSolution, problem, param);

    % Independent brute-force audit of the two-state DP kernel.
    if R <= cfg.subsetDpMaximumR
        assert(costsEqual(fixedOrderCost(nnOrder, problem), ...
            bruteForceDirectionCost(nnOrder, problem)), ...
            'Two-state direction DP failed its exhaustive direction audit.');
    end

    rawRows(end+1, 1) = makeRawRow(instance, 1, ...
        'FIXED', 'Fixed order + fixed direction', 1, NaN, ...
        fixedSolution, fixedRuntime, 0, fixedJ, exactJ, ...
        routeLibrary); %#ok<AGROW>
    rawRows(end+1, 1) = makeRawRow(instance, 2, ...
        'NN_DP', 'Nearest neighbour-DP', 1, NaN, ...
        nnSolution, nnRuntime, 0, fixedJ, exactJ, ...
        routeLibrary); %#ok<AGROW>

    for runIndex = 1:cfg.independentGaRuns
        seed = cfg.gaSeed + R*100000 + instance.number*1000 + runIndex;
        timer = tic;
        [jointSolution, jointGenerations] = solveGeneticAlgorithm( ...
            problem, cfg.ga, seed, 'joint', nnSolution);
        jointRuntime = toc(timer);
        validateSolution(jointSolution, problem, param);
        if isfinite(exactJ)
            assert(jointSolution.J+costTolerance(exactJ) >= exactJ);
        end
        rawRows(end+1, 1) = makeRawRow(instance, 3, ...
            'JOINT_GA', 'Joint-encoding GA', runIndex, seed, ...
            jointSolution, jointRuntime, jointGenerations, fixedJ, ...
            exactJ, routeLibrary); %#ok<AGROW>

        seed = cfg.gaSeed + R*100000 + instance.number*1000 + ...
            500 + runIndex;
        timer = tic;
        [gaDpSolution, gaDpGenerations] = solveGeneticAlgorithm( ...
            problem, cfg.ga, seed, 'ga-dp', nnSolution);
        gaDpRuntime = toc(timer);
        validateSolution(gaDpSolution, problem, param);
        if isfinite(exactJ)
            assert(gaDpSolution.J+costTolerance(exactJ) >= exactJ);
        end
        rawRows(end+1, 1) = makeRawRow(instance, 4, ...
            'GA_DP', 'Proposed GA-DP', runIndex, seed, ...
            gaDpSolution, gaDpRuntime, gaDpGenerations, fixedJ, ...
            exactJ, routeLibrary); %#ok<AGROW>

        if mod(runIndex, 5) == 0 || runIndex == cfg.independentGaRuns
            fprintf(['  GA runs %2d/%d: joint J=%.2f, ', ...
                'GA-DP J=%.2f\n'], runIndex, cfg.independentGaRuns, ...
                jointSolution.J, gaDpSolution.J);
        end
    end

    if ~isempty(exactSolution)
        rawRows(end+1, 1) = makeRawRow(instance, 5, ...
            'EXACT', 'Exact optimum', 1, NaN, exactSolution, ...
            exactRuntime, 0, fixedJ, exactJ, routeLibrary); %#ok<AGROW>
    end
end

raw = struct2table(rawRows);
raw = sortrows(raw, {'ScaleR', 'InstanceNumber', 'MethodOrder', 'Run'});
instanceStatistics = aggregateWithinInstances(raw);
summary = aggregateAcrossInstances(instanceStatistics);
horizontalComparison = buildHorizontalComparisonTable(summary, cfg);
algorithmEffectiveness = buildAlgorithmEffectiveness(raw,summary,cfg);

writetable(raw, fullfile(outputDir, 'exp2a_raw_runs.csv'), ...
    'Encoding', 'UTF-8');
writetable(instanceStatistics, fullfile(outputDir, ...
    'exp2a_instance_statistics.csv'), 'Encoding', 'UTF-8');
writetable(summary, fullfile(outputDir, 'exp2a_summary.csv'), ...
    'Encoding', 'UTF-8');
writetable(horizontalComparison, fullfile(outputDir, ...
    'exp2a_three_method_table.csv'), 'Encoding', 'UTF-8');
writetable(algorithmEffectiveness,fullfile(outputDir, ...
    'exp2a_gadp_effectiveness.csv'),'Encoding','UTF-8');

metadata.generatedAt = datetime('now', 'TimeZone', 'Asia/Shanghai');
metadata.matlabVersion = version;
metadata.projectRoot = projectRoot;
metadata.dataDirectory = dataDir;
metadata.routeCacheUsed = cacheUsed;
metadata.elapsedSeconds = toc(experimentStart);
metadata.costDefinition = ['J = integral of the directed 3-D multirotor ', ...
    'power model of Gong et al. (2023), reported in kJ'];
metadata.boundaryDefinition = ['Distinct fixed launch/recovery flight ', ...
    'points at opposite ends of measured manuscript Road A'];
metadata.fixedOrderDefinition = ...
    'Unoptimized source order: layer, feature ID, then window start';
save(fullfile(outputDir, 'exp2a_results.mat'), 'raw', ...
    'instanceStatistics', 'summary', 'horizontalComparison', ...
    'algorithmEffectiveness', ...
    'instances', 'instanceTable', 'routeLibrary', 'launchPoint', ...
    'recoveryPoint', 'masterProblem', ...
    'param', 'cfg', 'metadata');

finalAudit(raw, instanceStatistics, summary, instances, ...
    routeLibrary, param, cfg);

fprintf('\nExperiment 2a completed in %.1f min. Results written to:\n  %s\n', ...
    metadata.elapsedSeconds/60, outputDir);
disp(summary(:, {'ScaleR', 'MethodLabel', 'TaskInstances', ...
    'RunsPerInstance', 'J_MeanPlusMinusSD', 'Improvement_MeanPlusMinusSD_pct', ...
    'Gap_MeanPlusMinusSD_pct', 'Runtime_MeanPlusMinusSD_s'}));
disp(horizontalComparison);
end

%% Optimization methods

function problem = buildRoutingProblem(routes,launchPoint,recoveryPoint,param,terrain)
R = numel(routes);
entry = zeros(R, 2, 3);
exitPoint = zeros(R, 2, 3);
entryVelocity = zeros(R,2,3);
exitVelocity = zeros(R,2,3);
internalL = zeros(R, 2);
internalH = zeros(R, 2);
internalJ = zeros(R, 2);
internalTime = zeros(R,2);
for r = 1:R
    waypoints = routes(r).waypoints;
    assert(size(waypoints, 1) >= 2 && size(waypoints, 2) == 3);
    for direction = 1:2
        if direction == 1
            path = waypoints;
        else
            path = flipud(waypoints);
        end
        entry(r, direction, :) = path(1, :);
        exitPoint(r, direction, :) = path(end, :);
        firstTangent = unitVector(path(2,:)-path(1,:));
        lastTangent = unitVector(path(end,:)-path(end-1,:));
        entryVelocity(r,direction,:) = param.photographySpeed*firstTangent;
        exitVelocity(r,direction,:) = param.photographySpeed*lastTangent;
        for waypoint = 1:size(path,1)-1
            [energy_kJ,length3D,climb,time_s] = legMetrics( ...
                path(waypoint,:),path(waypoint+1,:),param,true);
            internalJ(r,direction) = internalJ(r,direction)+energy_kJ;
            internalL(r,direction) = internalL(r,direction)+length3D;
            internalH(r,direction) = internalH(r,direction)+climb;
            internalTime(r,direction) = internalTime(r,direction)+time_s;
        end
    end
end

depotEntryL = zeros(R, 2);
depotEntryH = zeros(R, 2);
depotEntryJ = zeros(R, 2);
depotEntryTime = zeros(R,2);
exitDepotL = zeros(R, 2);
exitDepotH = zeros(R, 2);
exitDepotJ = zeros(R, 2);
exitDepotTime = zeros(R,2);
transitionL = inf(R, 2, R, 2);
transitionH = inf(R, 2, R, 2);
transitionJ = inf(R, 2, R, 2);
transitionTime = inf(R,2,R,2);
transitionMinimumClearance = inf(R,2,R,2);
transitionDirectMinimumClearance = inf(R,2,R,2);
transitionDetour = false(R,2,R,2);
transitionPath = cell(R,2,R,2);
depotEntryPath = cell(R,2);
exitDepotPath = cell(R,2);
depotEntryMinimumClearance = inf(R,2);
depotEntryDirectMinimumClearance = inf(R,2);
depotEntryDetour = false(R,2);
exitDepotMinimumClearance = inf(R,2);
exitDepotDirectMinimumClearance = inf(R,2);
exitDepotDetour = false(R,2);
zeroVelocity = [0,0,0];
if isempty(gcp('nocreate'))
    parpool('threads');
end
parfor r = 1:R
    for d = 1:2
        e = reshape(entry(r, d, :), 1, 3);
        x = reshape(exitPoint(r, d, :), 1, 3);
        ue = reshape(entryVelocity(r,d,:),1,3);
        ux = reshape(exitVelocity(r,d,:),1,3);
        first = uav_terrain_transition(launchPoint,e,zeroVelocity,ue, ...
            terrain,param);
        last = uav_terrain_transition(x,recoveryPoint,ux,zeroVelocity, ...
            terrain,param);
        [depotEntryJ(r,d),depotEntryL(r,d),depotEntryH(r,d), ...
            depotEntryTime(r,d),depotEntryPath{r,d}] = unpackTransition(first);
        [exitDepotJ(r,d),exitDepotL(r,d),exitDepotH(r,d), ...
            exitDepotTime(r,d),exitDepotPath{r,d}] = unpackTransition(last);
        depotEntryMinimumClearance(r,d) = first.minimumClearance_m;
        depotEntryDirectMinimumClearance(r,d) = ...
            first.directMinimumClearance_m;
        depotEntryDetour(r,d) = first.detour;
        exitDepotMinimumClearance(r,d) = last.minimumClearance_m;
        exitDepotDirectMinimumClearance(r,d) = ...
            last.directMinimumClearance_m;
        exitDepotDetour(r,d) = last.detour;
        for s = 1:R
            if s == r
                continue;
            end
            for q = 1:2
                nextEntry = reshape(entry(s, q, :), 1, 3);
                nextVelocity = reshape(entryVelocity(s,q,:),1,3);
                result = uav_terrain_transition(x,nextEntry,ux, ...
                    nextVelocity,terrain,param);
                [transitionJ(r,d,s,q),transitionL(r,d,s,q), ...
                    transitionH(r,d,s,q),transitionTime(r,d,s,q), ...
                    transitionPath{r,d,s,q}] = unpackTransition(result);
                transitionMinimumClearance(r,d,s,q) = ...
                    result.minimumClearance_m;
                transitionDirectMinimumClearance(r,d,s,q) = ...
                    result.directMinimumClearance_m;
                transitionDetour(r,d,s,q) = result.detour;
            end
        end
    end
end

problem.R = R;
problem.launchPoint = launchPoint;
problem.recoveryPoint = recoveryPoint;
problem.entry = entry;
problem.exit = exitPoint;
problem.entryVelocity = entryVelocity;
problem.exitVelocity = exitVelocity;
problem.internalL = internalL;
problem.internalH = internalH;
problem.internalJ = internalJ;
problem.internalTime = internalTime;
problem.depotEntryL = depotEntryL;
problem.depotEntryH = depotEntryH;
problem.depotEntryJ = depotEntryJ;
problem.depotEntryTime = depotEntryTime;
problem.depotEntryPath = depotEntryPath;
problem.depotEntryMinimumClearance = depotEntryMinimumClearance;
problem.depotEntryDirectMinimumClearance = depotEntryDirectMinimumClearance;
problem.depotEntryDetour = depotEntryDetour;
problem.exitDepotL = exitDepotL;
problem.exitDepotH = exitDepotH;
problem.exitDepotJ = exitDepotJ;
problem.exitDepotTime = exitDepotTime;
problem.exitDepotPath = exitDepotPath;
problem.exitDepotMinimumClearance = exitDepotMinimumClearance;
problem.exitDepotDirectMinimumClearance = exitDepotDirectMinimumClearance;
problem.exitDepotDetour = exitDepotDetour;
problem.transitionL = transitionL;
problem.transitionH = transitionH;
problem.transitionJ = transitionJ;
problem.transitionTime = transitionTime;
problem.transitionPath = transitionPath;
problem.transitionMinimumClearance = transitionMinimumClearance;
problem.transitionDirectMinimumClearance = transitionDirectMinimumClearance;
problem.transitionDetour = transitionDetour;
problem.requiredClearance = param.terrain.clearance+ ...
    param.terrain.demErrorMargin;
end

function [energy_kJ,length3D,climb,time_s] = legMetrics( ...
    firstPoint,secondPoint,param,fixedPhotographySpeed)
if fixedPhotographySpeed
    [energy_kJ,length3D,climb,details] = uav_edge_energy( ...
        firstPoint,secondPoint,param.energy, ...
        'HorizontalSpeed',param.photographySpeed);
else
    [energy_kJ,length3D,climb,details] = ...
        uav_edge_energy(firstPoint,secondPoint,param.energy);
end
time_s = details.time_s;
end

function unit = unitVector(vector)
if norm(vector) <= 1e-12
    unit = [0,0,0];
else
    unit = vector/norm(vector);
end
end

function [energy,length3D,climb,time_s,path] = unpackTransition(result)
energy = result.energy_kJ;
length3D = result.length3D_m;
climb = result.climb_m;
time_s = result.time_s;
path = result.path;
end

function problem = subsetRoutingProblem(master,indices)
problem.R = numel(indices);
problem.launchPoint = master.launchPoint;
problem.recoveryPoint = master.recoveryPoint;
two = 1:2;
problem.entry = master.entry(indices,two,:);
