%% Task-set construction and measured-road waypoint library

function instances = buildTaskInstances(routeLibrary, cfg)
librarySize = numel(routeLibrary);
eligibleIndices = 2:librarySize;
instances = repmat(struct('R', 0, 'number', 0, 'id', '', ...
    'libraryIndices', []), 0, 1);
for scale = cfg.scales
    assert(numel(eligibleIndices) >= scale, ...
        'The route library is too small for distinct R=%d combinations.', scale);
    stream = RandStream('mt19937ar', ...
        'Seed', cfg.taskSeed+1000*scale);
    usedKeys = strings(0, 1);
    attempts = 0;
    while sum([instances.R] == scale) < cfg.taskInstancesPerScale
        attempts = attempts+1;
        assert(attempts <= 10000, ...
            'Could not generate enough unique real-road task sets.');
        sampled = eligibleIndices(randperm(stream,numel(eligibleIndices),scale));
        key = join(string(sort(sampled)), '-');
        if any(usedKeys == key)
            continue;
        end
        selected = sourceRegistrationOrder(sampled, routeLibrary);
        number = sum([instances.R] == scale)+1;
        item.R = scale;
        item.number = number;
        item.id = sprintf('R%02d_I%02d', scale, number);
        item.libraryIndices = selected;
        instances(end+1, 1) = item; %#ok<AGROW>
        usedKeys(end+1, 1) = key; %#ok<AGROW>
    end
end
end

