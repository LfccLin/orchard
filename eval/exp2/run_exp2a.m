function roads = analyseShapeSet(shapes, reference, dem, roadCRS, ...
    param, sourceLayer)
roads = repmat(emptyRoad(), numel(shapes), 1);
for index = 1:numel(shapes)
    road = emptyRoad();
    road.sourceLayer = sourceLayer;
    road.featureId = index;
    [x, y] = longestFinitePart(shapes(index).X, shapes(index).Y);
    if numel(x) < 2
        roads(index) = road;
        continue;
    end
    duplicate = [false; hypot(diff(x), diff(y)) < 1e-6];
    x(duplicate) = [];
    y(duplicate) = [];
    sourceProgress = [0; cumsum(hypot(diff(x), diff(y)))];
    if numel(sourceProgress) < 2 || ...
            sourceProgress(end) < 2*param.centerlineSpacing
        roads(index) = road;
        continue;
    end
    progress = (0:param.centerlineSpacing:sourceProgress(end))';
    if progress(end) < sourceProgress(end)
        progress(end+1, 1) = sourceProgress(end); %#ok<AGROW>
    end
    xq = interp1(sourceProgress, x, progress, 'pchip');
    yq = interp1(sourceProgress, y, progress, 'pchip');
    [latitude, longitude] = projinv(roadCRS, xq, yq);
    [xi, yi] = geographicToIntrinsic(reference, latitude, longitude);
    zRaw = interp2(dem, xi, yi, 'linear', NaN);
    if mean(isfinite(zRaw)) < 0.90
        roads(index) = road;
        continue;
    end
    zRaw = fillmissing(zRaw, 'linear', 'EndValues', 'nearest');
    window = max(3, round(param.elevationSmooth/param.centerlineSpacing));
    if mod(window, 2) == 0
        window = window+1;
    end
    z = smoothdata(zRaw, 'movmean', window);
    road = computeGeometry(road, progress, xq, yq, z);
    road.zRaw = zRaw;
    road.valid = true;
    roads(index) = road;
end
end

function candidates = buildCandidates(roads, param)
candidates = repmat(emptyRoad(), 0, 1);
localProgress = (0:param.centerlineSpacing:param.routeLength)';
for roadIndex = 1:numel(roads)
    road = roads(roadIndex);
    if ~road.valid || road.length < param.routeLength
        continue;
    end
    offsets = 0:param.windowStride:(road.length-param.routeLength);
    finalOffset = road.length-param.routeLength;
    if abs(offsets(end)-finalOffset) > 1e-8
        offsets(end+1) = finalOffset; %#ok<AGROW>
    end
    for offsetIndex = 1:numel(offsets)
        queryProgress = offsets(offsetIndex)+localProgress;
        candidate = road;
        candidate.startOffset = offsets(offsetIndex);
        candidate.endOffset = offsets(offsetIndex)+param.routeLength;
        x = interp1(road.s, road.x, queryProgress, 'pchip');
        y = interp1(road.s, road.y, queryProgress, 'pchip');
        z = interp1(road.s, road.z, queryProgress, 'linear');
        candidate = computeGeometry(candidate, localProgress, x, y, z);
        candidate.zRaw = interp1( ...
            road.s, road.zRaw, queryProgress, 'linear');
        candidate.valid = true;
        candidates(end+1, 1) = candidate; %#ok<AGROW>
    end
end
end

function road = computeGeometry(road, progress, x, y, z)
road.s = progress-progress(1);
road.x = x;
road.y = y;
road.z = z;
dx = gradient(x, road.s);
dy = gradient(y, road.s);
dz = gradient(z, road.s);
road.psi = unwrap(atan2(dy, dx));
road.alpha = atan2(dz, hypot(dx, dy));
road.kappa = gradient(road.psi, road.s);
road.length = road.s(end);
road.elevRange = max(z)-min(z);
road.totalTurn = trapz(road.s, abs(road.kappa));
road.absGradeP95 = percentile(abs(tan(road.alpha)), 95);
road.centroidX = mean(x);
road.centroidY = mean(y);
end

function [x, y] = longestFinitePart(X, Y)
finitePoints = isfinite(X) & isfinite(Y);
edges = diff([false, finitePoints, false]);
starts = find(edges == 1);
stops = find(edges == -1)-1;
if isempty(starts)
    x = [];
    y = [];
    return;
end
[~, index] = max(stops-starts+1);
x = X(starts(index):stops(index));
y = Y(starts(index):stops(index));
x = x(:);
y = y(:);
end

function value = percentile(values, percentage)
values = sort(values(isfinite(values)));
if isempty(values)
    value = NaN;
    return;
end
position = numel(values)*percentage/100+0.5;
position = min(max(position, 1), numel(values));
lower = floor(position);
upper = ceil(position);
if lower == upper
    value = values(lower);
else
    value = values(lower)+(position-lower)*(values(upper)-values(lower));
end
end

