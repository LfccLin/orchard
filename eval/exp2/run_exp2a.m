function value = meanFinite(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
else
    value = mean(values);
end
end

function value = stdFinite(values)
values = values(isfinite(values));
if isempty(values)
    value = NaN;
elseif isscalar(values)
    value = 0;
else
    value = std(values, 0);
end
end

function formatted = formatPlusMinus(means, standardDeviations, decimals)
formatted = strings(size(means));
pattern = sprintf('%%.%df %c %%.%df', decimals, char(177), decimals);
for index = 1:numel(means)
    if isfinite(means(index)) && isfinite(standardDeviations(index))
        formatted(index) = sprintf(pattern, ...
            means(index), standardDeviations(index));
    else
        formatted(index) = "--";
    end
end
end

