function solution = evaluateSolution(order, directions, problem)
R = problem.R;
assert(numel(order) == R && numel(unique(order)) == R);
assert(all(sort(order) == 1:R));
assert(numel(directions) == R && all(ismember(directions, [1, 2])));

firstRoad = order(1);
firstDirection = directions(1);
length3D = problem.depotEntryL(firstRoad, firstDirection);
climb = problem.depotEntryH(firstRoad, firstDirection);
energy = problem.depotEntryJ(firstRoad, firstDirection);
time_s = problem.depotEntryTime(firstRoad,firstDirection);
transferEnergy = energy;
transferLength = length3D;
detourCount = double(problem.depotEntryDetour(firstRoad,firstDirection));
unsafeDirectCount = double(problem.depotEntryDirectMinimumClearance( ...
    firstRoad,firstDirection) < problem.requiredClearance-1e-6);
minimumClearance = problem.depotEntryMinimumClearance( ...
    firstRoad,firstDirection);
for position = 1:R
    road = order(position);
    direction = directions(position);
    length3D = length3D+problem.internalL(road, direction);
    climb = climb+problem.internalH(road, direction);
    energy = energy+problem.internalJ(road,direction);
    time_s = time_s+problem.internalTime(road,direction);
    if position < R
        nextRoad = order(position+1);
        nextDirection = directions(position+1);
        length3D = length3D+problem.transitionL( ...
            road, direction, nextRoad, nextDirection);
        climb = climb+problem.transitionH( ...
            road, direction, nextRoad, nextDirection);
        energy = energy+problem.transitionJ( ...
            road,direction,nextRoad,nextDirection);
        time_s = time_s+problem.transitionTime( ...
            road,direction,nextRoad,nextDirection);
        transferEnergy = transferEnergy+problem.transitionJ( ...
            road,direction,nextRoad,nextDirection);
        transferLength = transferLength+problem.transitionL( ...
            road,direction,nextRoad,nextDirection);
        detourCount = detourCount+double(problem.transitionDetour( ...
            road,direction,nextRoad,nextDirection));
        unsafeDirectCount = unsafeDirectCount+double( ...
            problem.transitionDirectMinimumClearance( ...
            road,direction,nextRoad,nextDirection) < ...
            problem.requiredClearance-1e-6);
        minimumClearance = min(minimumClearance, ...
            problem.transitionMinimumClearance( ...
            road,direction,nextRoad,nextDirection));
    else
        length3D = length3D+problem.exitDepotL(road, direction);
        climb = climb+problem.exitDepotH(road, direction);
        energy = energy+problem.exitDepotJ(road,direction);
        time_s = time_s+problem.exitDepotTime(road,direction);
        transferEnergy = transferEnergy+problem.exitDepotJ(road,direction);
        transferLength = transferLength+problem.exitDepotL(road,direction);
        detourCount = detourCount+double( ...
            problem.exitDepotDetour(road,direction));
        unsafeDirectCount = unsafeDirectCount+double( ...
            problem.exitDepotDirectMinimumClearance(road,direction) < ...
            problem.requiredClearance-1e-6);
        minimumClearance = min(minimumClearance, ...
            problem.exitDepotMinimumClearance(road,direction));
    end
end

solution.order = double(order(:)');
solution.directions = double(directions(:)');
solution.L3D = length3D;
solution.Hplus = climb;
solution.J = energy;
solution.Time_s = time_s;
solution.TransferEnergy_kJ = transferEnergy;
solution.TransferLength_m = transferLength;
solution.DetourCount = detourCount;
solution.UnsafeDirectCount = unsafeDirectCount;
solution.MinimumTransferClearance_m = minimumClearance;
end

function cost = fixedOrderCost(order, problem)
R = problem.R;
previous = inf(1, 2);
firstRoad = order(1);
for direction = 1:2
    previous(direction) = problem.depotEntryJ(firstRoad, direction)+ ...
        problem.internalJ(firstRoad, direction);
end
for position = 2:R
    road = order(position);
    precedingRoad = order(position-1);
    current = inf(1, 2);
    for direction = 1:2
        transition = [problem.transitionJ( ...
            precedingRoad, 1, road, direction), ...
            problem.transitionJ(precedingRoad, 2, road, direction)];
        alternatives = previous+transition;
        current(direction) = min(alternatives)+ ...
            problem.internalJ(road, direction);
    end
    previous = current;
end
lastRoad = order(end);
cost = min(previous+problem.exitDepotJ(lastRoad, :));
end

function solution = solveFixedOrderDP(order, problem)
R = problem.R;
dp = inf(R, 2);
parent = zeros(R, 2, 'uint8');
firstRoad = order(1);
for direction = 1:2
    dp(1, direction) = problem.depotEntryJ(firstRoad, direction)+ ...
        problem.internalJ(firstRoad, direction);
end
for position = 2:R
    road = order(position);
    precedingRoad = order(position-1);
    for direction = 1:2
        transition = [problem.transitionJ( ...
            precedingRoad, 1, road, direction), ...
            problem.transitionJ(precedingRoad, 2, road, direction)];
        alternatives = dp(position-1, :)+transition;
        [best, predecessor] = min(alternatives);
        dp(position, direction) = best+problem.internalJ(road, direction);
        parent(position, direction) = uint8(predecessor);
    end
end
[~, lastDirection] = min(dp(R, :)+problem.exitDepotJ(order(end), :));
directions = zeros(1, R);
directions(R) = lastDirection;
for position = R:-1:2
    directions(position-1) = parent(position, directions(position));
end
solution = evaluateSolution(order, directions, problem);
assert(costsEqual(solution.J, fixedOrderCost(order, problem)));
end

function order = nearestNeighbourOrder(problem)
R = problem.R;
remaining = true(1, R);
order = zeros(1, R);
currentRoad = 0;
currentDirection = 0;
for position = 1:R
    bestKey = [inf, inf, inf];
    bestRoad = 0;
    bestDirection = 0;
    for road = find(remaining)
        for direction = 1:2
            if position == 1
                linkCost = problem.depotEntryJ(road, direction);
            else
                linkCost = problem.transitionJ( ...
                    currentRoad, currentDirection, road, direction);
            end
            key = [linkCost, road, direction];
            if lexicographicallyLess(key, bestKey)
                bestKey = key;
                bestRoad = road;
                bestDirection = direction;
            end
        end
    end
    order(position) = bestRoad;
    remaining(bestRoad) = false;
    currentRoad = bestRoad;
    currentDirection = bestDirection;
end
end

function yes = lexicographicallyLess(a, b)
firstDifference = find(a ~= b, 1, 'first');
yes = ~isempty(firstDifference) && a(firstDifference) < b(firstDifference);
end

function solution = solveExactSubsetDP(problem)
R = problem.R;
assert(R <= 20, 'Subset DP is intended only for small validation cases.');
stateCount = 2^R;
dp = inf(stateCount, R, 2);
parentRoad = zeros(stateCount, R, 2, 'uint16');
parentDirection = zeros(stateCount, R, 2, 'uint8');

for road = 1:R
    mask = bitset(uint32(0), road);
    for direction = 1:2
        dp(double(mask)+1, road, direction) = ...
            problem.depotEntryJ(road, direction)+ ...
            problem.internalJ(road, direction);
    end
end

fullMask = uint32(stateCount-1);
for maskValue = uint32(1):fullMask
    maskIndex = double(maskValue)+1;
    for lastRoad = 1:R
        if ~bitget(maskValue, lastRoad)
            continue;
        end
        for lastDirection = 1:2
            previousCost = dp(maskIndex, lastRoad, lastDirection);
            if ~isfinite(previousCost)
                continue;
            end
            for nextRoad = 1:R
                if bitget(maskValue, nextRoad)
                    continue;
                end
                nextMask = bitset(maskValue, nextRoad);
                nextIndex = double(nextMask)+1;
                for nextDirection = 1:2
                    candidate = previousCost+problem.transitionJ( ...
                        lastRoad, lastDirection, nextRoad, nextDirection)+ ...
                        problem.internalJ(nextRoad, nextDirection);
                    if candidate < dp(nextIndex, nextRoad, nextDirection)
                        dp(nextIndex, nextRoad, nextDirection) = candidate;
                        parentRoad(nextIndex, nextRoad, nextDirection) = ...
                            uint16(lastRoad);
                        parentDirection(nextIndex, nextRoad, nextDirection) = ...
                            uint8(lastDirection);
                    end
                end
            end
        end
    end
end

bestCost = inf;
lastRoad = 0;
lastDirection = 0;
finalIndex = stateCount;
for road = 1:R
    for direction = 1:2
        candidate = dp(finalIndex, road, direction)+ ...
            problem.exitDepotJ(road, direction);
        if candidate < bestCost
            bestCost = candidate;
            lastRoad = road;
            lastDirection = direction;
        end
    end
end

order = zeros(1, R);
directions = zeros(1, R);
maskValue = fullMask;
for position = R:-1:1
    order(position) = lastRoad;
    directions(position) = lastDirection;
    maskIndex = double(maskValue)+1;
    previousRoad = parentRoad(maskIndex, lastRoad, lastDirection);
    previousDirection = parentDirection(maskIndex, lastRoad, lastDirection);
    maskValue = bitset(maskValue, lastRoad, 0);
    lastRoad = double(previousRoad);
    lastDirection = double(previousDirection);
end
solution = evaluateSolution(order, directions, problem);
assert(costsEqual(solution.J, bestCost));
end

function solution = solveExactMILP(problem, settings)
% Exact directed generalized-TSP formulation. Each road contributes one of
% two direction states. Degree constraints select one state per road, and
% MTZ order constraints eliminate disconnected subtours.
R = problem.R;
stateCount = 2*R;
cursor = 0;
yIndex = cursor+(1:stateCount);
cursor = cursor+stateCount;
startIndex = cursor+(1:stateCount);
cursor = cursor+stateCount;
finishIndex = cursor+(1:stateCount);
cursor = cursor+stateCount;

arcIndex = zeros(stateCount, stateCount);
for firstState = 1:stateCount
    firstRoad = ceil(firstState/2);
    for secondState = 1:stateCount
        secondRoad = ceil(secondState/2);
        if firstRoad ~= secondRoad
            cursor = cursor+1;
            arcIndex(firstState, secondState) = cursor;
        end
    end
end
lastBinary = cursor;
orderIndex = cursor+(1:R);
cursor = cursor+R;
variableCount = cursor;

objective = zeros(variableCount, 1);
for state = 1:stateCount
    road = ceil(state/2);
    direction = mod(state-1, 2)+1;
    objective(yIndex(state)) = problem.internalJ(road, direction);
    objective(startIndex(state)) = problem.depotEntryJ(road, direction);
    objective(finishIndex(state)) = problem.exitDepotJ(road, direction);
end
for firstState = 1:stateCount
    firstRoad = ceil(firstState/2);
    firstDirection = mod(firstState-1, 2)+1;
    for secondState = 1:stateCount
        variable = arcIndex(firstState, secondState);
        if variable == 0
            continue;
        end
        secondRoad = ceil(secondState/2);
        secondDirection = mod(secondState-1, 2)+1;
        objective(variable) = problem.transitionJ( ...
            firstRoad, firstDirection, secondRoad, secondDirection);
    end
end

% One direction state per road; selected states have exactly one incoming
% and one outgoing arc, including the depot arcs.
equalityCount = R+2*stateCount+2;
equality = spalloc(equalityCount, variableCount, ...
    2*R+2*stateCount*(stateCount+1)+2*stateCount);
equalityRight = zeros(equalityCount, 1);
row = 0;
for road = 1:R
    row = row+1;
    states = 2*(road-1)+(1:2);
    equality(row, yIndex(states)) = 1; %#ok<SPRIX>
    equalityRight(row) = 1;
end
for state = 1:stateCount
    row = row+1;
    equality(row, startIndex(state)) = 1; %#ok<SPRIX>
    incoming = arcIndex(:, state);
    incoming = incoming(incoming > 0);
    equality(row, incoming) = 1; %#ok<SPRIX>
    equality(row, yIndex(state)) = -1; %#ok<SPRIX>

    row = row+1;
    equality(row, finishIndex(state)) = 1; %#ok<SPRIX>
    outgoing = arcIndex(state, :);
    outgoing = outgoing(outgoing > 0);
    equality(row, outgoing) = 1; %#ok<SPRIX>
    equality(row, yIndex(state)) = -1; %#ok<SPRIX>
end
row = row+1;
equality(row, startIndex) = 1;
equalityRight(row) = 1;
row = row+1;
equality(row, finishIndex) = 1;
equalityRight(row) = 1;
assert(row == equalityCount);

% If an inter-road arc r->s is selected, position(s)>=position(r)+1.
arcVariables = nonzeros(arcIndex);
inequalityCount = numel(arcVariables);
inequality = spalloc(inequalityCount, variableCount, 3*inequalityCount);
inequalityRight = (R-1)*ones(inequalityCount, 1);
row = 0;
for firstState = 1:stateCount
    firstRoad = ceil(firstState/2);
    for secondState = 1:stateCount
        variable = arcIndex(firstState, secondState);
        if variable == 0
            continue;
        end
        row = row+1;
        secondRoad = ceil(secondState/2);
        inequality(row, orderIndex(firstRoad)) = 1; %#ok<SPRIX>
        inequality(row, orderIndex(secondRoad)) = -1; %#ok<SPRIX>
        inequality(row, variable) = R; %#ok<SPRIX>
    end
end
assert(row == inequalityCount);

lowerBound = zeros(variableCount, 1);
upperBound = ones(variableCount, 1);
lowerBound(orderIndex) = 1;
upperBound(orderIndex) = R;
integerVariables = 1:lastBinary;

% A feasible direction-optimized nearest-neighbour tour is supplied only
% as a warm start; it does not alter the exact MILP feasible region.
warmSolution = solveFixedOrderDP(nearestNeighbourOrder(problem), problem);
initial = zeros(variableCount, 1);
states = 2*(warmSolution.order-1)+warmSolution.directions;
initial(yIndex(states)) = 1;
initial(startIndex(states(1))) = 1;
initial(finishIndex(states(end))) = 1;
for position = 1:R-1
    initial(arcIndex(states(position), states(position+1))) = 1;
end
for position = 1:R
    initial(orderIndex(warmSolution.order(position))) = position;
end

options = optimoptions('intlinprog', 'Display', 'off', ...
    'RelativeGapTolerance', settings.relativeGapTolerance, ...
    'AbsoluteGapTolerance', settings.absoluteGapTolerance, ...
    'MaxTime', settings.maximumTime_s);
[variables, objectiveValue, exitFlag, output] = intlinprog( ...
    objective, integerVariables, inequality, inequalityRight, ...
    equality, equalityRight, lowerBound, upperBound, initial, options);
assert(exitFlag == 1, ...
    ['Exact MILP did not certify global optimality. Exit flag %d, ', ...
    'relative gap %.6g.'], exitFlag, output.relativegap);

firstState = find(variables(startIndex) > 0.5);
assert(isscalar(firstState));
order = zeros(1, R);
directions = zeros(1, R);
state = firstState;
for position = 1:R
    order(position) = ceil(state/2);
    directions(position) = mod(state-1, 2)+1;
    if position < R
        variablesFromState = arcIndex(state, :);
        candidates = find(variablesFromState > 0);
        selected = candidates(variables( ...
            variablesFromState(candidates)) > 0.5);
        assert(isscalar(selected));
        state = selected;
    else
        assert(variables(finishIndex(state)) > 0.5);
    end
end

solution = evaluateSolution(order, directions, problem);
assert(costsEqual(solution.J, objectiveValue));
solution.exactSolver = 'MILP';
solution.solverRelativeGap_pct = output.relativegap;
solution.solverAbsoluteGap = output.absolutegap;
solution.solverNodes = output.numnodes;
end

function [solution, generation] = solveGeneticAlgorithm( ...
    problem, ga, seed, mode, heuristicSolution)
R = problem.R;
stream = RandStream('mt19937ar', 'Seed', seed);
populationSize = ga.populationSize;
orders = zeros(populationSize, R);
directionsByRoad = ones(populationSize, R, 'uint8');

orders(1, :) = 1:R;
orders(2, :) = heuristicSolution.order;
heuristicDirectionByRoad = ones(1, R, 'uint8');
heuristicDirectionByRoad(heuristicSolution.order) = ...
    uint8(heuristicSolution.directions);
directionsByRoad(2, :) = heuristicDirectionByRoad;
for individual = 3:populationSize
    orders(individual, :) = randperm(stream, R);
    if strcmp(mode, 'joint')
        directionsByRoad(individual, :) = uint8( ...
            1+(rand(stream, 1, R) >= 0.5));
    end
end

fitness = evaluatePopulation(orders, directionsByRoad, problem, mode);
[bestCost, bestIndex] = min(fitness);
bestOrder = orders(bestIndex, :);
bestDirectionByRoad = directionsByRoad(bestIndex, :);
stall = 0;

for generation = 1:ga.maximumGenerations
    [~, ranking] = sort(fitness, 'ascend');
    newOrders = zeros(size(orders));
    newDirections = ones(size(directionsByRoad), 'uint8');
    elite = ranking(1:ga.eliteCount);
    newOrders(1:ga.eliteCount, :) = orders(elite, :);
    newDirections(1:ga.eliteCount, :) = directionsByRoad(elite, :);

    writeIndex = ga.eliteCount+1;
    while writeIndex <= populationSize
        firstParent = tournamentSelect(fitness, ga.tournamentSize, stream);
        secondParent = tournamentSelect(fitness, ga.tournamentSize, stream);
        child1 = orders(firstParent, :);
        child2 = orders(secondParent, :);
        direction1 = directionsByRoad(firstParent, :);
        direction2 = directionsByRoad(secondParent, :);

        if rand(stream) < ga.crossoverRate
            [child1, child2] = orderCrossover(child1, child2, stream);
            if strcmp(mode, 'joint')
                takeFirst = rand(stream, 1, R) < 0.5;
                oldDirection1 = direction1;
                direction1(~takeFirst) = direction2(~takeFirst);
                direction2(~takeFirst) = oldDirection1(~takeFirst);
            end
        end
        child1 = mutatePermutation(child1, ...
            ga.permutationMutationRate, stream);
        child2 = mutatePermutation(child2, ...
            ga.permutationMutationRate, stream);
        if strcmp(mode, 'joint')
            direction1 = mutateDirections(direction1, 1/R, stream);
            direction2 = mutateDirections(direction2, 1/R, stream);
        end

        newOrders(writeIndex, :) = child1;
        newDirections(writeIndex, :) = direction1;
        if writeIndex+1 <= populationSize
            newOrders(writeIndex+1, :) = child2;
            newDirections(writeIndex+1, :) = direction2;
        end
        writeIndex = writeIndex+2;
    end

    orders = newOrders;
    directionsByRoad = newDirections;
    fitness = evaluatePopulation(orders, directionsByRoad, problem, mode);
    [generationBest, generationIndex] = min(fitness);
    if generationBest < bestCost-ga.improvementTolerance*max(1, abs(bestCost))
        bestCost = generationBest;
        bestOrder = orders(generationIndex, :);
        bestDirectionByRoad = directionsByRoad(generationIndex, :);
        stall = 0;
    else
        stall = stall+1;
    end
    if generation >= ga.minimumGenerations && stall >= ga.stallGenerations
        break;
    end
end

if strcmp(mode, 'ga-dp')
    solution = solveFixedOrderDP(bestOrder, problem);
else
    bestDirections = double(bestDirectionByRoad(bestOrder));
    solution = evaluateSolution(bestOrder, bestDirections, problem);
end
assert(costsEqual(solution.J, bestCost));
end

function fitness = evaluatePopulation(orders, directionsByRoad, problem, mode)
populationSize = size(orders, 1);
fitness = inf(populationSize, 1);
for individual = 1:populationSize
    order = orders(individual, :);
    if strcmp(mode, 'ga-dp')
        fitness(individual) = fixedOrderCost(order, problem);
    else
        directions = double(directionsByRoad(individual, order));
        solution = evaluateSolution(order, directions, problem);
        fitness(individual) = solution.J;
    end
end
end

function index = tournamentSelect(fitness, tournamentSize, stream)
competitors = randi(stream, numel(fitness), 1, tournamentSize);
[~, localIndex] = min(fitness(competitors));
index = competitors(localIndex);
end

function [child1, child2] = orderCrossover(parent1, parent2, stream)
R = numel(parent1);
cuts = sort(randperm(stream, R, 2));
first = cuts(1);
last = cuts(2);
child1 = oxChild(parent1, parent2, first, last);
child2 = oxChild(parent2, parent1, first, last);
end

function child = oxChild(primary, secondary, first, last)
R = numel(primary);
child = zeros(1, R);
child(first:last) = primary(first:last);
slots = [last+1:R, 1:first-1];
scan = [secondary(last+1:R), secondary(1:last)];
remaining = scan(~ismember(scan, child(first:last)));
child(slots) = remaining;
assert(numel(unique(child)) == R && all(sort(child) == 1:R));
end

function chromosome = mutatePermutation(chromosome, rate, stream)
if rand(stream) >= rate
    return;
end
positions = sort(randperm(stream, numel(chromosome), 2));
if rand(stream) < 0.5
    chromosome(positions(1):positions(2)) = ...
        chromosome(positions(2):-1:positions(1));
else
    chromosome(positions) = chromosome(fliplr(positions));
end
end

function directions = mutateDirections(directions, rate, stream)
flip = rand(stream, size(directions)) < rate;
directions(flip) = uint8(3)-directions(flip);
end

function bestCost = bruteForceDirectionCost(order, problem)
R = problem.R;
bestCost = inf;
for code = 0:(2^R-1)
    directions = 1+bitget(uint32(code), 1:R);
    solution = evaluateSolution(order, directions, problem);
    bestCost = min(bestCost, solution.J);
end
end

function bestCost = bruteForceAllCost(problem)
R = problem.R;
assert(R <= 5);
orders = perms(1:R);
bestCost = inf;
for row = 1:size(orders, 1)
    bestCost = min(bestCost, ...
        bruteForceDirectionCost(orders(row, :), problem));
end
end

function validateSolution(solution, problem, ~)
