function units = selectNonOverlappingCandidateUnits( ...
    paperRoadA, majorCandidates, minorCandidates)
pool = [majorCandidates(:); minorCandidates(:)];
layerRank = 2*ones(numel(pool), 1);
layerRank(strcmp({pool.sourceLayer}, 'Major')) = 1;
sorting = table(layerRank, [pool.featureId]', [pool.startOffset]', ...
    (1:numel(pool))', 'VariableNames', ...
    {'Layer', 'Feature', 'Start', 'Original'});
sorting = sortrows(sorting, {'Layer', 'Feature', 'Start'});
pool = pool(sorting.Original);

units = paperRoadA;
for index = 1:numel(pool)
    candidate = pool(index);
    conflict = false;
    for selectedIndex = 1:numel(units)
        selected = units(selectedIndex);
        if strcmp(candidate.sourceLayer, selected.sourceLayer) && ...
                candidate.featureId == selected.featureId
            overlap = min(candidate.endOffset, selected.endOffset)- ...
                max(candidate.startOffset, selected.startOffset);
            if overlap > 1e-8
                conflict = true;
                break;
            end
        end
    end
    if ~conflict
        units(end+1, 1) = candidate; %#ok<AGROW>
    end
end
end

function order = maximinCandidateOrder(candidates)
count = numel(candidates);
coordinates = [[candidates.centroidX]', [candidates.centroidY]'];
scale = max(coordinates, [], 1)-min(coordinates, [], 1);
scale(scale <= 0) = 1;
coordinates = (coordinates-min(coordinates, [], 1))./scale;

order = zeros(1, count);
order(1) = 1; % measured manuscript Road A is the fixed anchor
selected = false(1, count);
selected(1) = true;
minimumDistance = vecnorm(coordinates-coordinates(1, :), 2, 2);
for position = 2:count
    score = minimumDistance;
    score(selected) = -inf;
    [~, next] = max(score);
    order(position) = next;
    selected(next) = true;
    distance = vecnorm(coordinates-coordinates(next, :), 2, 2);
    minimumDistance = min(minimumDistance, distance);
end
end

